// Generates TypeScript types for every operation in the catalogue (ADR-0007),
// so a changed operation breaks the web app's type check instead of drifting.
//
// Reads the catalogue as printed by `turtle catalogue` and writes
// src/lib/operations.gen.ts. Run through `npm run generate`; set CARGO to
// the cargo binary if it is not on the PATH.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

type Schema = {
  type?: string | string[]
  $ref?: string
  anyOf?: Schema[]
  oneOf?: Schema[]
  allOf?: Schema[]
  const?: unknown
  enum?: unknown[]
  properties?: Record<string, Schema>
  required?: string[]
  items?: Schema
  additionalProperties?: Schema | boolean
  description?: string
  title?: string
  $defs?: Record<string, Schema>
}

type Operation = {
  name: string
  description: string
  browser_only: boolean
  input: Schema
  output: Schema
}

const SIMPLE: Record<string, string> = {
  string: 'string',
  boolean: 'boolean',
  integer: 'number',
  number: 'number',
  null: 'null',
}

/** The TypeScript for a schema, for the subset of JSON Schema that schemars emits. */
export function typeOf(schema: Schema | boolean, indent = ''): string {
  if (schema === true) return 'unknown'
  if (schema === false) return 'never'
  if (schema.$ref) return schema.$ref.replace(/^#\/\$defs\//, '')
  const union = schema.anyOf ?? schema.oneOf
  if (union) return union.map(part => typeOf(part, indent)).join(' | ')
  if (schema.allOf) return schema.allOf.map(part => typeOf(part, indent)).join(' & ')
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ')
  if (Array.isArray(schema.type)) {
    return schema.type.map(type => typeOf({ ...schema, type }, indent)).join(' | ')
  }
  if (schema.type === 'array') return `${wrap(typeOf(schema.items ?? true, indent))}[]`
  if (schema.type === 'object') {
    const properties = Object.entries(schema.properties ?? {})
    if (properties.length === 0) {
      const extra = schema.additionalProperties
      return extra && extra !== true ? `Record<string, ${typeOf(extra, indent)}>` : 'Record<string, never>'
    }
    const inner = indent + '  '
    const lines = properties.map(([name, property]) => {
      const optional = schema.required?.includes(name) ? '' : '?'
      const doc = property.description ? `${inner}/** ${property.description} */\n` : ''
      return `${doc}${inner}${name}${optional}: ${typeOf(property, inner)}`
    })
    return `{\n${lines.join('\n')}\n${indent}}`
  }
  if (typeof schema.type === 'string' && schema.type in SIMPLE) return SIMPLE[schema.type]
  return 'unknown'
}

function wrap(type: string): string {
  return /^[\w.]+$/.test(type) ? type : `(${type})`
}

/** The schema with every reference to its own root (`#`) pointing at `name` instead. */
function selfReferenced(schema: Schema, name: string): Schema {
  return JSON.parse(JSON.stringify(schema), (key, value) =>
    key === '$ref' && value === '#' ? `#/$defs/${name}` : value,
  )
}

/**
 * The type of an operation's output. An output with a title is named after it,
 * so the web app can refer to it and it can contain itself.
 */
function outputType(schema: Schema, definitions: Map<string, string>): string {
  if (!schema.title || schema.type !== 'object') return typeOf(schema, '    ')
  const title = schema.title
  // Only the shape: definitions are collected separately, and the
  // description and title belong to the operation, not the type.
  const { type, properties, required, additionalProperties } = selfReferenced(schema, title)
  define(definitions, title, typeOf({ type, properties, required, additionalProperties }))
  return title
}

/**
 * Names a type. The catalogue's types are named after their Rust structs,
 * and two structs of the same name in different modules would otherwise
 * leave the web app with whichever came last.
 */
function define(definitions: Map<string, string>, name: string, type: string) {
  const known = definitions.get(name)
  if (known !== undefined && known !== type) {
    throw new Error(
      `Two different types are named ${name}. Rename one of the Rust types so every name is unique.\n\n${known}\n\n${type}`,
    )
  }
  definitions.set(name, type)
}

export function generate(operations: Operation[]): string {
  const definitions = new Map<string, string>()
  for (const operation of operations) {
    for (const schema of [operation.input, operation.output]) {
      for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
        define(definitions, name, typeOf(definition))
      }
    }
  }
  const outputs = operations.map(operation => outputType(operation.output, definitions))
  const out = ['// Generated by scripts/generate-operations.ts from the operation catalogue. Do not edit.', '']
  for (const [name, type] of [...definitions].sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`export type ${name} = ${type}`, '')
  }
  out.push('/** Every operation, with its input and output. */', 'export type Operations = {')
  for (const [index, operation] of operations.entries()) {
    out.push(
      `  /** ${operation.description} */`,
      `  ${operation.name}: {`,
      `    input: ${typeOf(operation.input, '    ')}`,
      `    output: ${outputs[index]}`,
      '  }',
    )
  }
  out.push('}', '')
  return out.join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const manifest = fileURLToPath(new URL('../../server/Cargo.toml', import.meta.url))
  // CARGO names the cargo binary when it is not on the PATH.
  const printed = execFileSync(
    process.env.CARGO ?? 'cargo',
    ['run', '--quiet', '--manifest-path', manifest, '--', 'catalogue'],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
  )
  const target = fileURLToPath(new URL('../src/lib/operations.gen.ts', import.meta.url))
  writeFileSync(target, generate(JSON.parse(printed).operations))
  console.log(`wrote ${target}`)
}
